/**
 * 締めの問いの直前に置く受け止め。締めの問いだけを出すと、直前に話した大事な話に一言も触れずに
 * 話題が変わり、聞いてもらえなかった感じが残る。受け止めは別のメッセージとして生成し、
 * 締めの問いの文面は変えない。問いが混ざった場合は lib/conversation.ts で取り除く。
 */
export const ACKNOWLEDGE_INSTRUCTION =
  "学習者の直前の発言を、話した言葉を拾って受け止める短い言葉（1〜2文）だけを返してください。このあとシステムが締めの問いを出すので、問いは含めないこと。「〜という気持ちがあったんですね。」のような言い切りの形で返すこと。";

/**
 * 次に試すこと（action_plan）を本人に問う。質問会議ではアクションプランを問題提示者自身が出すので、
 * LLM に行動計画を作らせない。評価で使う問いではないので固定せず、締めの答えを受け止めて会話の流れで聞く。
 * 締めの答えで問題が無くなることもあるので、問題があることを前提にしない。
 */
export const ACTION_PLAN_INSTRUCTION = [
  "学習者が締めの問いに答えたところです。その答えを短く受け止めたうえで、次のPBL活動で試してみたいことを、本人の言葉で聞いてください。",
  "試すことの例や候補を挙げないこと（助言になるため）。問題があることを前提にしないこと。",
  QUESTION_RULE,
].join(" ");

/**
 * Try は、本人が「次に試すこと」として答えた内容を、本人の言葉のまま整理したもの。LLM は行動を足さない。
 * 言っていない行動を作らない・他者への要望を本人の行動に書き換えない・試すことが出なければ作らない、の3点は
 * いずれも試用で実際に起きた崩れへの対処。
 */
export const TRY_PLAN_INSTRUCTION = [
  "学習者が「次に試すこと」として答えた内容を中心に、メモもあわせて、次回のPBLで本人が試すことを、学習者自身の言葉をできるだけそのまま使って3項目以内で整理してください。",
  "学習者が言っていない行動や方針を作らないこと。「〜してほしかった」という他者への要望を、「〜を伝える」のような本人の行動に書き換えないこと。",
  "本人が試すことを答えていない場合（「特にない」「問題あったっけ？」など）は、「（今回は、次に試すことは決まりませんでした）」とだけ出力すること。",
  "それ以外は「- 」で始まる箇条書きの行だけを出力し、見出しや前置き、太字（**）などの装飾は使わないこと。",
].join(" ");

/** Try を頼む最後の発話（会話を user で終えるため） */
export const TRY_PLAN_REQUEST = "ここまでの対話から、次回のPBLで試すことを整理してください。";
