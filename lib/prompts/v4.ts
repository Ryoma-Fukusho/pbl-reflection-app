/**
 * AI に生成させず、全参加者に一字一句同じ文言を提示する2つの発話。
 * DB には generated: false で記録され、分析時に生成文と機械的に分離できる。
 */
export const FIXED_MESSAGES = {
  /**
   * 対話の最初の一言。まだ学生の発言が無く生成の材料が無いため固定。
   * 加えて、全参加者の入り口を揃える意味もある。v1 から変更なし。
   */
  opening:
    "今日のPBL活動、おつかれさまでした。この時間は、あなたの中にあるものを一緒に言葉にしていく時間です。まずは、うまくいったこと・続けたいと思ったことから聞かせてください。",

  /**
   * 対話の締めくくりの問い。
   *
   * この問いへの回答が sessions.closingInsight に入り、内省の深さを測る主要データになる。
   * AI に生成させると問いの表現が参加者ごとに変わり、回答の差が「内省の差」なのか
   * 「問いの差」なのか分離できなくなるため固定文言にしている。
   *
   * v3 での変更: 質問会議の「問題の再定義」（問題提示者が、質問されたことを通して
   * あらためて現在の問題は何かを提示する）の問い方に寄せた。
   * v2 は「あなた自身が主体的に向き合うべき『本当の課題』」と尋ねており、
   * 原因を自分に向けることを問いの側が前提にしていた。これだと回答が自己に向いても
   * 内省の結果なのか問いへの迎合なのか分けられず、原因が本当に外にある場合にまで
   * 自責を促すおそれがある。どこに原因を見るかは学習者に委ねる。
   */
  closing_insight:
    "ここまでの対話、ありがとうございました。最後にひとつお聞きします。ここまで問いに答えてきたことを通して、あらためて、いまの問題は何だと思いますか？",
} as const;

/**
 * 各ステージで AI に何を引き出させるか。COMMON_SYSTEM に続けて渡される。
 *
 * keep は FIXED_MESSAGES.opening、closing_insight は FIXED_MESSAGES.closing_insight を
 * 使うため、実際に Claude へ渡されるのは problem / fact / feeling_other / essence の4つ。
 * （keep と closing_insight も定義だけは置いて、ステージ列との対応を崩さない）
 */
export const STAGE_INSTRUCTIONS: Record<DialogueStage, string> = {
  keep: "学生が今日うまくいったこと・続けたいことを話しやすいように問いかけてください。",

  // v4 での変更: Keep の答えの中で、すでに引っかかったことが語られている場合がある。
  // そのときは同じことを聞き直さず、どれが一番気になっているかを選ばせる。
  problem:
    "現在のステージは problem です。今日の活動で引っかかったこと・モヤモヤしたことを尋ねる問いを1つだけ返してください。学習者がすでに引っかかったことを話している場合は、聞き直さず、その中で一番気になっていることはどれかを尋ねてください。",

  // v4 での変更: 「具体的にどう動いたか」が、手の動きや作業ペースのような細部を尋ねる問いを招いた。
  // 出来事と、本人が何をしたか・しなかったかに絞る。対象は Problem で挙がった問題の場面に固定する。
  fact: "現在のステージは fact です。Problem として学習者が挙げた問題の場面について、そのとき何が起き、自分は何をしたか（誰に何を言ったか、何をしなかったか）を思い出させる問いを1つだけ返してください。評価や解釈ではなく出来事の想起を促すこと。体の動きや作業のペースのような細部は尋ねないこと。例: そのとき、あなたは相手に何と返しましたか？",

  // v2 での変更: v1 は「自身の感情」と「相手からの見え方」の両方を要求しており、
  // COMMON_SYSTEM の「問いかけは必ず1つだけ」と衝突していた。
  // 他責的な問題認識を崩す鍵は他者視点（脱中心化）なので、そちらに一本化する。
  // 感情の想起は fact ステージでの事実の語り直しの中で自然に現れる分に委ねる。
  //
  // 識別子 feeling_other は変更しないこと。改名すると v1 で収集したデータとの
  // 対応が切れる。論文・UI 上の呼称は「相手の視点」で統一する。
  // v4 での変更: 相手を Problem の場面にかかわった人に限定した（話がずれた先の「周りの人」にしない）。
  feeling_other:
    "現在のステージは feeling_other です。Problem として学習者が挙げた問題の場面にかかわった相手（リーダーやメンバーなど）の側から見たときに、自分の行動や状況がどう映っていたかに目を向けさせる問いを1つだけ返してください。相手の表情や様子を尋ねるのではなく、相手の側から見た自分の映り方を尋ねること。例: リーダーから見ると、あのときのあなたの返事はどう映っていたと思いますか？",

  // v2 での変更: 「表面ではなく」を「表面的な不満ではなく」と具体化し、
  // 引き出す対象を「本質的な願いや目的」と明示した。不満の吐き出しで止まらせないため。
  essence:
    "現在のステージは essence です。Problem として学習者が挙げた問題について、出来事の表面的な不満ではなく、その背後で本人が本当はどうしたかったのか（本質的な願いや目的）を引き出す問いを1つだけ返してください。相手にどうしてほしかったかではなく、本人がどうしたかったかを尋ねること。例: 本当は、あなたはその状況でどうしたかったのでしょうか？",

  closing_insight:
    "現在のステージは closing_insight です。ここまでの対話を通して、あらためていまの問題は何だと思うかを尋ねてください。",
};

/**
 * 進め方 B で、学習者が「この話を続ける」を選んだときの指示。STAGE_INSTRUCTIONS の代わりに渡す。
 *
 * ステージの観点は変えずに掘り下げさせる。次のステージの観点を先取りされると、
 * 学習者が「次の問いへ進む」を選んだときに同じことを2回聞かれることになる。
 * closing_insight は1回で答えるステージなので定義しない（締めの問いは固定文言のため）。
 */
export const FOLLOWUP_INSTRUCTIONS: Record<Exclude<DialogueStage, "closing_insight">, string> = {
  keep: "うまくいったこと・続けたいこと",
  problem: "今日の活動で引っかかったこと・モヤモヤしたこと",
  fact: "その場面で実際に何が起き、自分が具体的にどう動いたか（評価や解釈ではなく事実）",
  feeling_other: "その場面で、相手の側から自分の行動や状況がどう映っていたか",
  essence: "出来事の背後で、本人が本当はどうしたかったのか（本質的な願いや目的）",
};

export function followupInstruction(stage: Exclude<DialogueStage, "closing_insight">): string {
  return [
    `現在のステージは ${stage} のままです。学習者は、この観点についてもう少し話すことを選びました。`,
    `観点は「${FOLLOWUP_INSTRUCTIONS[stage]}」です。`,
    // v4 での変更: v3 は「直前の発言を受けて」掘り下げさせたため、脇道の話題を追いかけて
    // Problem の問題から離れていった。掘り下げる対象を問題の場面に固定する。
    stage === "keep"
      ? "うまくいったことが特にない、またはうまくいかなかったことを話した場合は、無理に良い面を探させず、それで構わないこと、困ったことは次の問いで聞くことを伝えて「次の問いへ進む」を押すよう促してください。そうでなければ、話してくれたことを掘り下げる問いを1つだけ返してください。"
      : "Problem として学習者が挙げた問題の場面について、この観点の中でまだ語られていないことを尋ねる問いを1つだけ返してください。直前の発言がその問題から離れていたら、問題の場面に戻す問いにしてください。",
    "これまでに尋ねた問いと同じ問いを繰り返さないこと。別の観点の問いに移らないこと。",
    "直前の答えが「特にない」「覚えていない」など短いものだった場合は、深追いせず、この観点はここまでで十分なので「次の問いへ進む」を押してよいと伝えてください。",
  ].join(" ");
}

