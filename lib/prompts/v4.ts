import type { DialogueStage } from "@/lib/types";

/**
 * プロンプト定義 v4。
 *
 * v3 からの変更点と、その根拠は docs/prompt-design.md「変更履歴」を参照。
 * 進め方 B を開発者自身が試した対話（2026-10-27）で出た5つの崩れ方を直した:
 *   1. 褒める・良い意味づけをする（「やり遂げられた」「大きな発見ですね」）
 *   2. 気持ちや動機を推測して言い当てる、仮定を重ねて問いが読めなくなる
 *   3. 直前の発言だけを追いかけて、Problem で挙がった問題から話がずれる
 *   4. 「覚えてない」「特にない」を受け止めずに言い換えて聞き直す、細部（手の動き・作業ペース）を尋ねる
 *   5. Try が本人の言っていない行動を作る、見出しや太字を使う
 *
 * 構成の方針:
 *   COMMON_SYSTEM は「常に載るふるまいの制約」、STAGE_INSTRUCTIONS と
 *   FOLLOWUP_INSTRUCTIONS と TRY_PLAN_INSTRUCTION は「そのターン固有の役割」だけを持つ。
 *   両者の連結は lib/conversation.ts が行う。ここでは連結済みの文字列を作らない。
 *
 * v2.ts / v3.ts は書き換えないこと。書き換えると「どの版で集めたデータか」の対応が切れる。
 */
export const PROMPT_VERSION = "v4";

