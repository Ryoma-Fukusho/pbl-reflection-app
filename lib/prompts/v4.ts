/** 振り返りの前提文脈。会話の先頭に置いて、以後の応答の土台にする。v1 から変更なし。 */
export function buildContextText(keep: string, problem: string, memo: string): string {
  return [
    "以下は振り返りの前提文脈です。以後の応答は必ずこの文脈を踏まえてください。",
    `Keep: ${keep || "未入力"}`,
    `Problem: ${problem || "未入力"}`,
    `Memo: ${memo || "未入力"}`,
  ].join("\n");
}
