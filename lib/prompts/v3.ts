/**
 * プロンプト定義 v3。
 *
 * v2 からの変更点と、その根拠は docs/prompt-design.md「変更履歴」を参照。
 * 要約すると2点:
 *   1. 締めの問いを質問会議の「問題の再定義」の問い方に寄せた。
 *      v2 の「あなた自身が主体的に向き合うべき『本当の課題』」は自己への帰属を
 *      前提にしており、回答が問いへの迎合になりうるうえ、自責を促すおそれがあった
 *   2. 進め方 B（各ステージで話す回数を学習者が決める）のために、
 *      同じステージの中で掘り下げる問いの指示 FOLLOWUP_INSTRUCTIONS を追加した
 *
 * 構成の方針:
 *   COMMON_SYSTEM は「常に載るふるまいの制約」、STAGE_INSTRUCTIONS と
 *   FOLLOWUP_INSTRUCTIONS と TRY_PLAN_INSTRUCTION は「そのターン固有の役割」だけを持つ。
 *   両者の連結は lib/conversation.ts が行う。ここでは連結済みの文字列を作らない。
 *
 * v2.ts は書き換えないこと。書き換えると「どの版で集めたデータか」の対応が切れる。
 */
export const PROMPT_VERSION = "v3";

