/**
 * v2 での変更: 「AI が新しい助言を足さない」ことを明文化した。
 *
 * v1 は対話中だけ助言を禁じ、最後に AI が行動計画を提示していたため、
 * 「結局 AI が答えを出しているのでは」という指摘に実装で反論できなかった。
 * v2 では Try を「新規の助言」ではなく「学習者自身の発話の再構成・要約」と定義し、
 * 各項目が本人の発話に根拠を持つことを要求する。
 *
 * 「対話の終盤で語られた課題」という書き方にしているのは、この指示が統制群にも
 * 適用されるため。統制群には closing_insight ステージが無いので、条件によらず
 * 成立する言い方にしてある。
 */
export const TRY_PLAN_INSTRUCTION = [
  "Turn FINAL です。AI から新しい助言や一般論の解決策を追加してはいけません。",
  "これまでの対話の中で学習者自身が気づき、述べた内容（特に対話の終盤で語られた課題）およびメモ欄の内容を統合し、次回のPBLで本人が意識すべき具体的な行動計画（Try）として再構成・要約して箇条書きで出力してください。",
  "各項目は、学習者自身が対話の中で述べた内容に根拠を持つものだけにすること。",
  "この出力に限り、箇条書きを使ってよい。",
].join(" ");

export const FINAL_USER_PROMPT = [
  "これまでのチャット履歴とメモを踏まえて、次回のPBLで意識する Try を箇条書きで整理してください。",
  "新しい助言を加えず、学習者自身が対話の中で述べた内容だけを材料にしてください。",
].join("\n");

/** 振り返りの前提文脈。会話の先頭に置いて、以後の応答の土台にする。v1 から変更なし。 */
export function buildContextText(keep: string, problem: string, memo: string): string {
  return [
    "以下は振り返りの前提文脈です。以後の応答は必ずこの文脈を踏まえてください。",
    `Keep: ${keep || "未入力"}`,
    `Problem: ${problem || "未入力"}`,
    `Memo: ${memo || "未入力"}`,
  ].join("\n");
}
