  "shallow = 同じところに留まり、短い答えや表面的な答えが続いている。",
  "covered: 現在のステージの観点のうち、学習者の発言からすでに分かっているもの。観点の文言をそのまま書く。ほかのステージで語られた内容から分かるものも含めてよい。",
